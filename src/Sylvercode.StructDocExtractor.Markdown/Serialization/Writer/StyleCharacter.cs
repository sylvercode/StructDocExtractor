namespace Sylvercode.StructDocExtractor.Markdown.Serialization.Writer;

/// <summary>Specifies the character used to delimit an inline Markdown style marker.</summary>
public enum StyleCharacter
{
    /// <summary>Uses the asterisk character (<c>*</c>) as the style delimiter.</summary>
    Asterisk,
    /// <summary>Uses the underscore character (<c>_</c>) as the style delimiter.</summary>
    Underscore
}
